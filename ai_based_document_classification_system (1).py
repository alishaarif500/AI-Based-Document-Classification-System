import pickle
import numpy as np
import re
import string
from nltk.tokenize import word_tokenize
from nltk.stem import WordNetLemmatizer
from nltk.corpus import stopwords

# 1. Load the saved assets
with open('models/logistic_regression.pkl', 'rb') as f:
    model_lr = pickle.load(f)

with open('models/multinomial_nb.pkl', 'rb') as f:
    model_nb = pickle.load(f)

with open('models/tfidf_vectorizer.pkl', 'rb') as f:
    loaded_vectorizer = pickle.load(f)

with open('models/categories.pkl', 'rb') as f:
    class_names = pickle.load(f)

# 2. Re-verify the preprocessing pipeline is available
lemmatizer = WordNetLemmatizer()
stop_words = set(stopwords.words('english'))

def preprocess_text(text):
    text = text.lower()
    text = re.sub(r'\d+', '', text)
    text = text.translate(str.maketrans('', '', string.punctuation))
    tokens = word_tokenize(text)
    cleaned_tokens = [lemmatizer.lemmatize(token) for token in tokens if token not in stop_words]
    return ' '.join(cleaned_tokens)

# 3. Define the prediction function
def predict_category(text, model_name='nb'):
    # Select model
    model = model_nb if model_name.lower() == 'nb' else model_lr
    model_label = "Multinomial Naive Bayes" if model_name.lower() == 'nb' else "Logistic Regression"

    # Clean and vectorize
    cleaned = preprocess_text(text)
    vectorized = loaded_vectorizer.transform([cleaned])

    # Predict class and probabilities
    pred_class = model.predict(vectorized)[0]
    probabilities = model.predict_proba(vectorized)[0]

    print(f"\nInput Text: \"{text}\"")
    print(f"Model Used: {model_label}")
    print(f"Predicted Category: {pred_class.upper()} (Confidence: {probabilities[class_names.index(pred_class)]:.2%})")
    print("Confidence Scores per Category:")
    for category, prob in zip(class_names, probabilities):
         print(f"  - {category}: {prob:.2%}")
    print("-" * 50)
    return pred_class, probabilities

# 4. Test with mock news statements
